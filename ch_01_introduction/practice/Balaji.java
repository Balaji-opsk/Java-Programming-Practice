package core_java.basics.ch_01_introduction.practice;

public class Balaji {
	public static void main(String[] args) {
		System.out.println("`");
		System.out.println("!");
		System.out.println("@");
		System.out.println("#");
		System.out.println("$");
		System.out.println("%");
		System.out.println("^");
		System.out.println("&");
		System.out.println("*");
		System.out.println("(");
		System.out.println(")");
		System.out.println("{");
		System.out.println("_");
		System.out.println("+");
		System.out.println("}");
		System.out.println(":");
		System.out.println("/");
		System.out.println("\\\\");
//		System.out.println("\");this shows an error
		System.out.println("\"");
		System.out.println(";");
		System.out.println("\"");
	
	}

}
